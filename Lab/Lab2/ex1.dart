void main() {
  //Int var
  int age = 21;

  //Double var
  double height = 1.6;

  //String var
  String name = "Thinh";

  //Bool var
  bool isStudent = true;

  //Print
  print("Name: $name");
  print("Age: $age");
  print("Height: $height");
  print("Is student: $isStudent");

  //String interpolation with expression
  print("Next year age: ${age + 1}");
}
